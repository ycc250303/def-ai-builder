CREATE TABLE plants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id),
    nickname VARCHAR(100) NOT NULL CHECK (char_length(btrim(nickname)) > 0),
    species VARCHAR(100) NOT NULL CHECK (char_length(btrim(species)) > 0),
    planting_date DATE,
    care_start_date DATE NOT NULL,
    growing_location VARCHAR(7) CHECK (growing_location IN ('INDOOR', 'OUTDOOR')),
    cultivation_method VARCHAR(5) CHECK (cultivation_method IN ('SOIL', 'WATER')),
    description VARCHAR(1000)
);

CREATE INDEX plants_user_id_id_idx ON plants (user_id, id DESC);

COMMENT ON TABLE plants IS '用户植物档案';
COMMENT ON COLUMN plants.id IS '植物编号，数据库自增';
COMMENT ON COLUMN plants.user_id IS '所属用户，关联 users.id';
COMMENT ON COLUMN plants.nickname IS '昵称，留空时采用品种名称';
COMMENT ON COLUMN plants.species IS '用户填写的品种名称';
COMMENT ON COLUMN plants.planting_date IS '种植日期，未知时为空';
COMMENT ON COLUMN plants.care_start_date IS '开始养护日期，留空时由后端填入上海时区当天日期';
COMMENT ON COLUMN plants.growing_location IS '培养地：INDOOR 室内，OUTDOOR 室外，可空';
COMMENT ON COLUMN plants.cultivation_method IS '培养方式：SOIL 土培，WATER 水培，可空';
COMMENT ON COLUMN plants.description IS '简要描述，可空';
